namespace SignalCli.Models.SignalCli;

/// <summary>
/// Стан процесу Signal CLI.
/// </summary>
/// <remarks>
/// Визначає можливі стани життєвого циклу процесу,
/// які використовуються для відстеження його роботи.
/// </remarks>
public enum ProcessState
{
    /// <summary>
    /// Процес не запущено.
    /// </summary>
    /// <remarks>
    /// Початковий стан перед першим запуском або після завершення роботи.
    /// </remarks>
    NotStarted,
    
    /// <summary>
    /// Процес запускається.
    /// </summary>
    /// <remarks>
    /// Перехідний стан під час ініціалізації процесу.
    /// </remarks>
    Starting,
    
    /// <summary>
    /// Процес запущено та працює.
    /// </summary>
    /// <remarks>
    /// Нормальний робочий стан, який означає готовність процесу до обробки запитів.
    /// </remarks>
    Running,
    
    /// <summary>
    /// Процес зупиняється.
    /// </summary>
    /// <remarks>
    /// Перехідний стан під час штатного завершення роботи процесу.
    /// </remarks>
    Stopping,
    
    /// <summary>
    /// Процес зупинено.
    /// </summary>
    /// <remarks>
    /// Стан, що вказує на нормальне завершення роботи процесу.
    /// </remarks>
    Stopped,
    
    /// <summary>
    /// Сталася помилка під час роботи процесу.
    /// </summary>
    /// <remarks>
    /// Стан, що вказує на аварійне завершення роботи або інші проблеми.
    /// </remarks>
    Failed
}